pal = {'.':None,'K':(60,40,35),'O':(240,160,80),'D':(205,120,55),'P':(255,175,180),
       'W':(255,255,255),'C':(255,240,220),'N':(230,110,120),'R':(255,140,140)}
rows=[r for r in art.strip('\n').split('\n')]
W,H=32,32
img=Image.new('RGB',(W,H),(255,232,200))
# 背景に市松模様の床
for y in range(H):
    for x in range(W):
        if y>=29: img.putpixel((x,y),(225,190,150) if (x//2+y)%2 else (210,175,135))
for y,r in enumerate(rows):
    for x,ch in enumerate(r.ljust(W,'.')[:W]):
        c=pal.get(ch)
        if c: img.putpixel((x,y),c)
img.resize((W*24,H*24),Image.NEAREST).save('pixelcat.png')
